// Idempotent upserts preserve custom entries and work across connections/restarts.
export async function ensureCandidateOptions() {
  await CandidateOption.init();
  await CandidateOption.bulkWrite(
    Object.entries(defaults).flatMap(([kind, names]) =>
      names.map((name) => ({
        updateOne: {
          filter: { kind, nameKey: keyOf(name) },
          update: { $setOnInsert: { kind, name, nameKey: keyOf(name) } },
          upsert: true,
        },
      })),
    ),
  );
}
